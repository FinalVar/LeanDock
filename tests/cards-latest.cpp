#include "cards-core-latest.h"
#include <cstdio>
#include <limits>
int main(){using namespace LeanDockCards;int count=0,failed=0;
    auto check=[&](bool ok,const char* name){++count;if(!ok){++failed;std::printf("FAIL %s\n",name);}};
    CommandGate gate;
    auto old=gate.Begin();check(old&&gate.busy,"first media command admitted");
    check(!gate.Begin(),"duplicate click is coalesced");
    gate.Invalidate();check(!gate.busy,"session switch releases previous player's busy state");
    auto current=gate.Begin();check(current&&current!=old,"new player can accept command immediately");
    check(!gate.Finish(old)&&gate.busy,"old completion cannot clear new player's command");
    check(gate.Finish(current)&&!gate.busy,"current completion releases buttons");
    check(!gate.Finish(current),"duplicate completion ignored");
    current=gate.Begin();gate.Invalidate();check(!gate.Finish(current)&&!gate.busy,"completion after Stop ignored");
    check(CpuPercent({100,150,100},{180,250,200})==60,"kernel includes idle");
    check(CpuPercent({0,0,0},{200,200,0})==0,"all idle");
    check(CpuPercent({0,0,0},{0,100,100})==100,"all busy");
    check(!CpuPercent({20,30,40},{20,30,40}),"zero interval");
    check(!CpuPercent({20,30,40},{19,35,45}),"idle counter reset");
    check(!CpuPercent({20,30,40},{25,29,45}),"kernel counter reset");
    check(!CpuPercent({20,30,40},{25,35,39}),"user counter reset");
    check(!CpuPercent({0,0,0},{300,100,100}),"inconsistent counters");
    CpuSampler sampler;
    check(!sampler.value,"no invented initial CPU value");
    sampler.Resume(CpuTimes{100,150,100},1000);
    check(sampler.refreshing&&sampler.IntervalMs()==200&&!sampler.value,"initial reading uses brief real warmup");
    check(!sampler.Sample(CpuTimes{180,250,200},1199)&&!sampler.value,"early queued tick cannot publish CPU");
    check(sampler.Sample(CpuTimes{180,250,200},1200)&&sampler.value==60,"first real sample after warmup");
    check(!sampler.refreshing&&sampler.IntervalMs()==2000,"steady sampling returns to low-frequency interval");
    sampler.Pause();check(sampler.value==60&&!sampler.baseline&&!sampler.refreshing,"hidden card keeps last value without collecting");
    sampler.Resume(CpuTimes{1000,2000,3000},9000);
    check(sampler.value==60&&sampler.refreshing,"resume retains cached value but marks it as refreshing");
    check(!sampler.Sample(CpuTimes{1100,2200,3100},9001)&&sampler.value==60,"old queued tick after resume cannot overwrite retained value");
    check(sampler.Sample(CpuTimes{1100,2200,3100},9200)&&sampler.value==67,"hidden interval excluded from resumed sample");
    check(sampler.Sample(CpuTimes{0,0,0},9400)&&!sampler.value,"counter reset clears CPU rather than presenting cached data as current");
    check(sampler.Sample(CpuTimes{0,100,100},9600)&&sampler.value==100,"valid counters recover after reset");
    check(!sampler.Sample(CpuTimes{0,150,150},9500)&&sampler.refreshing,"clock rollback establishes a new baseline");
    check(sampler.Sample({},9800)&&!sampler.value&&!sampler.refreshing,"unavailable counters clear cached CPU");
    sampler.value=50;sampler.Resume({},10000);
    check(!sampler.value&&!sampler.refreshing&&sampler.IntervalMs()==2000,"unsupported query does not loop at warmup frequency");
    const double edge=520+132+25+SlotWidth+24;
    check(Fits(edge+8,520,132,false),"enter with hysteresis");
    check(!Fits(edge+7,520,132,false),"avoid entering on fractional edge");
    check(Fits(edge+4,520,132,true),"keep slot with measurement guard");
    check(!Fits(edge,520,132,true),"collapse when app measurement hits cap");
    check(!Fits(1920,0,132,false),"wait for apps geometry");
    check(Fits(1920,520,0,false),"empty app tray is valid");
    check(!Fits(1920,520,-1,false),"invalid tray geometry");
    check(!Fits(std::numeric_limits<double>::quiet_NaN(),520,132,false),"reject nan geometry");
    check(Fits(800,52,76,false),"one app stays compact");
    const auto close=[](double a,double b){return std::abs(a-b)<0.000001;};
    check(!GaugeArc({}).visible,"unknown load has no invented ring fill");
    check(!GaugeArc(0).visible,"zero load has an empty track");
    auto arc=GaugeArc(25);check(arc.visible&&!arc.full&&!arc.large&&close(arc.x,RingSize/2+RingRadius)&&close(arc.y,RingSize/2),"quarter load ends at three oclock");
    arc=GaugeArc(50);check(!arc.large&&close(arc.x,RingSize/2)&&close(arc.y,RingSize/2+RingRadius),"half load ends at six oclock");
    arc=GaugeArc(75);check(arc.large&&close(arc.x,RingSize/2-RingRadius)&&close(arc.y,RingSize/2),"three-quarter load fills the large arc");
    check(GaugeArc(100).full&&GaugeArc(100).visible,"full load uses a whole circle instead of coincident arc endpoints");
    check(GaugeArc(300).full,"excess input clamps to full circle");
    bool ringBounds=true;
    for(unsigned i=1;i<100;++i){arc=GaugeArc(i);
        ringBounds=ringBounds&&arc.visible&&!arc.full&&std::isfinite(arc.x)&&std::isfinite(arc.y)&&
            close(std::hypot(arc.x-RingSize/2,arc.y-RingSize/2),RingRadius)&&
            arc.x>=RingStroke/2-0.000001&&arc.x<=RingSize-RingStroke/2+0.000001&&
            arc.y>=RingStroke/2-0.000001&&arc.y<=RingSize-RingStroke/2+0.000001;
    }
    check(ringBounds,"all intermediate loads stay on radius without clipping stroke");
    for(int a=0;a<2;++a)for(int b=0;b<2;++b)for(int c=0;c<2;++c)
        check(ShouldSample(a,b,c)==bool(a&&b&&c),"visible metrics active conjunction");
    int wheel=0;check(!WheelStep(30,wheel),"small wheel delta");check(!WheelStep(60,wheel),"accumulate partial wheel");
    check(WheelStep(30,wheel)==-1,"positive detent goes backward");check(wheel==0,"exact detent has no remainder");
    check(WheelStep(-240,wheel)==1,"large event advances only once");
    check(!WheelStep(60,wheel)&&!WheelStep(-60,wheel)&&wheel==0,"opposite partial deltas cancel");
    check(!WheelStep(80,wheel)&&WheelStep(80,wheel)==-1&&wheel==40,"fractional excess retained");
    check(WheelStep(80,wheel)==-1&&wheel==0,"remaining fraction completes another detent");
    check(!WheelStep(0,wheel)&&wheel==0,"zero wheel event does not switch");
    auto page=Page::Metrics;
    page=Cycle(page,1);check(page==Page::Media,"metrics to media regardless of session existence");
    page=Cycle(page,1);check(page==Page::Power,"media to battery in same slot");
    page=Cycle(page,1);check(page==Page::Clock,"battery to clock in same slot");
    page=Cycle(page,1);check(page==Page::Metrics,"forward wraps to metrics");
    page=Cycle(page,-1);check(page==Page::Clock,"backward wraps to clock");
    page=Cycle(page,-1);check(page==Page::Power,"backward from clock to battery");
    page=Cycle(page,-1);check(page==Page::Media,"backward to media");
    page=Cycle(page,-1);check(page==Page::Metrics,"backward to metrics");
    check(Cycle(page,0)==page,"partial wheel retains page");
    for(unsigned i=0;i<static_cast<unsigned>(Page::Count);++i){auto original=static_cast<Page>(i);
        check(Cycle(Cycle(original,1),-1)==original,"opposite detents restore every page");}
    check(ClockText(0,0,1,1).time==L"00:00"&&ClockText(0,0,1,1).date==L"01月01日","midnight and New Year formatting");
    check(ClockText(23,59,12,31).time==L"23:59"&&ClockText(23,59,12,31).date==L"12月31日","last minute of year");
    check(ClockText(6,8,2,29).time==L"06:08"&&ClockText(6,8,2,29).date==L"02月29日","leading zero and leap day");
    check(ClockText(24,0,1,1).time==L"—"&&ClockText(0,0,0,1).date==L"—","invalid clock values are not real time");
    check(NextMinuteMs(0,0)==60020&&NextMinuteMs(30,500)==29520,"clock schedules only next minute boundary");
    check(NextMinuteMs(59,999)==250&&NextMinuteMs(60,0)==60000,"clock avoids near-boundary busy loop");
    auto b=BatteryState(true,100,1,1);check(b.present&&b.percent==100&&b.plugged&&!b.charging,"full AC battery");
    b=BatteryState(true,33,8,1);check(b.percent==33&&b.charging,"charging");
    b=BatteryState(true,255,1,255);check(b.present&&b.percent==-1&&!b.plugged,"unknown percent and AC");
    b=BatteryState(true,0,128,1);check(!b.present&&b.percent==-1,"no battery is not zero percent");
    b=BatteryState(true,73,255,1);check(!b.charging&&b.percent==-1,"unknown flags are not charging");
    b=BatteryState(false,0,0,0);check(b.percent==-1,"failed power query is not zero percent");
    check(Mode(b)==BatteryMode::Unknown&&!b.presentKnown,"failed query is not no-battery");
    b=BatteryState(true,100,1,1);check(Mode(b)==BatteryMode::Full,"100 percent AC shows fully charged not charging");
    b=BatteryState(true,80,1,1);check(Mode(b)==BatteryMode::Plugged,"charge limit is plugged without charging");
    b=BatteryState(true,80,1,0);check(Mode(b)==BatteryMode::OnBattery,"unplugging updates visible state without percentage change");
    b=BatteryState(true,80,8,1);check(Mode(b)==BatteryMode::Charging,"replugging can update visible state without percentage change");
    b=BatteryState(true,80,1,1);check(Mode(b)==BatteryMode::Plugged&&!b.charging,"charge flag turning off retires lightning");
    b=BatteryState(true,20,1,0);check(Mode(b)==BatteryMode::Low,"low battery threshold");
    b=BatteryState(true,10,1,0);check(Mode(b)==BatteryMode::Critical,"critical battery threshold");
    b=BatteryState(true,21,2,0);check(Mode(b)==BatteryMode::Low,"driver low battery flag is respected");
    b=BatteryState(true,11,4,0);check(Mode(b)==BatteryMode::Critical,"driver critical battery flag is respected");
    b=BatteryState(true,5,12,1);check(Mode(b)==BatteryMode::Charging,"charging status takes precedence over low percentage");
    b=BatteryState(true,0,128,1);check(Mode(b)==BatteryMode::NoBattery&&!b.charging,"desktop AC is not an empty charging battery");
    b=BatteryState(true,73,255,1);check(Mode(b)==BatteryMode::Unknown&&b.plugged,"unknown battery still retains known AC state");
    b=BatteryState(true,73,1,255);check(Mode(b)==BatteryMode::Unknown&&b.percent==73,"unknown supply must not assert discharge");
    b=BatteryState(true,255,1,0);check(Mode(b)==BatteryMode::OnBattery&&!b.low&&!b.critical,"unknown percent is not low or critical");
    std::printf("Cards: %d checks, %d failures\n",count,failed);return failed?1:0;
}
